'use strict';
const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { spawnSync } = require('node:child_process');
const { GRANDFATHER_CUTOFF, GRANDFATHERED, checkMigrationSql, checkMigrations } = require('./check-migration-grants.cjs');

const decided = (table, privileges = 'select, insert, update, delete') => `
alter table public.${table} enable row level security;
revoke all on table public.${table} from anon, authenticated;
grant ${privileges} on table public.${table} to service_role;
`;

// Each passes: a new public table with RLS and an explicit decision for every role.
const PASSING = {
  'unquoted, qualified': `create table public.notes (id uuid primary key, body text);${decided('notes')}`,
  'if not exists, upper case': `CREATE TABLE IF NOT EXISTS PUBLIC.Notes (id uuid);
ALTER TABLE PUBLIC.NOTES ENABLE ROW LEVEL SECURITY;
GRANT SELECT ON PUBLIC.NOTES TO ANON, AUTHENTICATED;
REVOKE ALL ON TABLE notes FROM SERVICE_ROLE;`,
  'quoted identifiers': `create table "public"."notes" (id uuid);
alter table only "public"."notes" enable row level security;
grant select on table "public"."notes" to "anon";
revoke all on "notes" from "authenticated", "service_role";`,
  'unqualified, default search_path': `create table notes (id uuid);${decided('notes')}`,
  'one grant per role, separate statements': `create table public.notes (id uuid);
alter table if exists public.notes enable row level security;
grant select on public.notes to anon;
grant select, insert on public.notes to authenticated;
grant all on public.notes to service_role with grant option;`,
  'bigserial with its sequence': `create table public.events (id bigserial primary key);${decided('events')}
revoke all on sequence public.events_id_seq from anon, authenticated;
grant usage, select on sequence public.events_id_seq to service_role;`,
  'identity with its sequence': `create table public.events (
  id bigint generated always as identity primary key, at timestamptz default now()
);${decided('events')}
grant usage on sequence public.events_id_seq to anon, authenticated, service_role;`,
  'another schema is not public': `create table private.secrets (id serial primary key);`,
  'unqualified under another search_path': `set search_path = private, public;
create table secrets (id serial primary key);`,
  'temporary table': `create temp table scratch (id serial);`,
  'comments and strings that only mention create table': `-- create table public.ghost (id uuid);
/* create table public.ghost (id uuid); */
select 'create table public.ghost (id uuid)';`,
  'no table at all': `alter table public.dreams add column note text; grant select on public.dreams to anon;`,
  'identity with a custom sequence name': `create table public.events (
  id bigint generated by default as identity (sequence name public.event_ids start with 10) primary key
);${decided('events')}
grant usage on sequence public.event_ids to anon, authenticated, service_role;`,
  'view with a decision per role': `create or replace view public.dream_stats as select 1 as n;
grant select on public.dream_stats to authenticated;
revoke all on public.dream_stats from anon, service_role;`,
  'standalone sequence with a decision per role': `create sequence public.ticket_numbers;
grant usage on sequence public.ticket_numbers to service_role;
revoke all on sequence public.ticket_numbers from anon, authenticated;`,
  'a function body only runs when called': `create function public.make_ghost() returns void language sql
as $$ create table public.ghost (id uuid) $$;`,
  'qualified grant after another search_path': `create table public.notes (id uuid);
set search_path = private;
alter table public.notes enable row level security;
grant select on public.notes to anon, authenticated, service_role;`,
};

// Each fails with the listed problems.
const FAILING = {
  'no RLS': [`create table public.notes (id uuid);
grant select on public.notes to anon, authenticated, service_role;`, [/no "alter table public\.notes enable row level security"/]],
  'no grant at all': [`create table public.notes (id uuid); alter table public.notes enable row level security;`,
    [/no explicit grant or revoke on the table for anon, authenticated, service_role/]],
  'service_role forgotten': [`create table public.notes (id uuid);
alter table public.notes enable row level security;
revoke all on public.notes from anon, authenticated;`, [/for service_role$/]],
  'schema-wide grant is not a decision about the table': [`create table public.notes (id uuid);
alter table public.notes enable row level security;
grant select on all tables in schema public to anon, authenticated, service_role;`, [/for anon, authenticated, service_role/]],
  'grant to PUBLIC is not a role decision': [`create table public.notes (id uuid);
alter table public.notes enable row level security;
revoke all on public.notes from public;`, [/for anon, authenticated, service_role/]],
  'RLS on another table': [`create table public.notes (id uuid);
alter table public.other enable row level security;
grant select on public.notes to anon, authenticated, service_role;`, [/enable row level security/]],
  'quoted mixed case is another table': [`create table public."Notes" (id uuid);${decided('notes')}`,
    [/public\.Notes: no "alter table/, /public\.Notes: no explicit grant/]],
  'serial without its sequence grant': [`create table public.events (id serial primary key);${decided('events')}`,
    [/column id owns sequence public\.events_id_seq; no explicit grant or revoke on it for anon, authenticated, service_role/]],
  'identity with a partial sequence grant': [`create table if not exists public.events (
  n integer generated by default as identity, body text
);${decided('events')}
grant usage on sequence public.events_n_seq to service_role;`, [/sequence public\.events_n_seq; .* for anon, authenticated$/]],
  'unqualified under search_path public': [`set search_path to public;
create table notes (id uuid);`, [/public\.notes: no "alter table/, /public\.notes: no explicit grant/]],
  'created inside a DO block': [`do $$ begin
  create table if not exists public.notes (id uuid);
end $$;`, [/public\.notes: no "alter table/, /public\.notes: no explicit grant/]],
  'unqualified grant resolved to another schema': [`create table public.notes (id uuid);
alter table public.notes enable row level security;
set search_path = private;
grant select on notes to anon, authenticated, service_role;`, [/no explicit grant or revoke on the table for anon, authenticated, service_role/]],
  'RLS only inside a string': [`create table public.notes (id uuid);
grant select on public.notes to anon, authenticated, service_role;
select 'alter table public.notes enable row level security';`, [/no "alter table public\.notes enable row level security"/]],
  'RLS only inside a function body': [`create table public.notes (id uuid);
grant select on public.notes to anon, authenticated, service_role;
create function public.later() returns void language plpgsql as $fn$
begin alter table public.notes enable row level security; end $fn$;`, [/enable row level security/]],
  'identity with a custom name, conventional name granted': [`create table public.events (
  id bigint generated always as identity (sequence name event_ids)
);${decided('events')}
grant usage on sequence public.events_id_seq to anon, authenticated, service_role;`,
  [/column id owns sequence public\.event_ids; no explicit grant or revoke on it for anon, authenticated, service_role/]],
  'view without decisions': [`create materialized view public.dream_stats as select 1 as n;
grant select on public.dream_stats to authenticated;`, [/public\.dream_stats: no explicit grant or revoke on the view for anon, service_role/]],
  'standalone sequence without decisions': [`create sequence if not exists public.ticket_numbers;`,
    [/public\.ticket_numbers: no explicit grant or revoke on the sequence for anon, authenticated, service_role/]],
  'table moved into public': [`create table staging.notes (id uuid);
alter table staging.notes set schema public;`, [/public\.notes: no "alter table/, /public\.notes: no explicit grant/]],
  'unlogged table': [`create unlogged table public.cache (k text primary key);`, [/no "alter table public\.cache/, /public\.cache: no explicit grant/]],
};

test('a new public table, view or sequence with RLS (tables) and an explicit grant or revoke for each role passes', () => {
  for (const [name, sql] of Object.entries(PASSING)) assert.deepEqual(checkMigrationSql(sql), [], name);
});

test('a new public object missing RLS, a role decision or a sequence decision fails', () => {
  for (const [name, [sql, expected]] of Object.entries(FAILING)) {
    const problems = checkMigrationSql(sql);
    assert.equal(problems.length, expected.length, `${name}: ${problems.join(' | ')}`);
    expected.forEach((pattern, index) => assert.match(problems[index], pattern, name));
  }
});

function withMigrations(files, run) {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'migration-grants-'));
  try {
    for (const [file, sql] of Object.entries(files)) fs.writeFileSync(path.join(dir, file), sql);
    return run(dir);
  } finally {
    fs.rmSync(dir, { recursive: true, force: true });
  }
}

test('only grandfathered historical migrations may fail, and the list stays closed', () => {
  const bad = 'create table public.legacy (id uuid);';
  withMigrations({ '20251019163753_old.sql': bad, '20261021090000_new.sql': PASSING['unquoted, qualified'] }, (dir) => {
    assert.deepEqual(checkMigrations(dir, ['20251019163753_old.sql']), { files: 2, grandfathered: 1, failures: [], stale: [] });
    const strict = checkMigrations(dir, []);
    assert.deepEqual(strict.failures.map((failure) => failure.file), ['20251019163753_old.sql']);
    const passing = checkMigrations(dir, ['20251019163753_old.sql', '20261021090000_new.sql']);
    assert.match(passing.stale.join('\n'), /20261021090000_new\.sql: newer than 20261020001047/);
    assert.match(passing.stale.join('\n'), /20261021090000_new\.sql: grandfathered but passes/);
    assert.match(checkMigrations(dir, ['20251019163753_old.sql', '20250101000000_gone.sql']).stale.join('\n'), /gone\.sql: grandfathered but missing/);
  });
  withMigrations({ '20261022000000_new_table.sql': bad }, (dir) => {
    assert.deepEqual(checkMigrations(dir, []).failures.map((failure) => failure.file), ['20261022000000_new_table.sql']);
  });
});

test('the grandfathered list holds only migrations from before the rule', () => {
  assert.equal(GRANDFATHERED.length, 13);
  for (const file of GRANDFATHERED) assert.ok(file.slice(0, 14) <= GRANDFATHER_CUTOFF, file);
});

test('the repository migrations pass', () => {
  const result = spawnSync(process.execPath, [path.join(__dirname, 'check-migration-grants.cjs')], { encoding: 'utf8' });
  assert.equal(result.status, 0, result.stderr);
  assert.match(result.stdout, /13 grandfathered, 0 failures/);
});
