#!/usr/bin/env node
'use strict';

/**
 * Writes the app's manifest of symbol illustrations served by the marketing site.
 *
 * The marketing site already owns one illustration per symbol (docs-src), published
 * on noctalia.app in several widths. The app loads the width it needs from there and
 * expo-image keeps it in its disk cache, instead of shipping ~6 MB of artwork in the
 * binary. A symbol without artwork keeps the sky fallback. Re-run after the site adds
 * or replaces an illustration:
 *
 *   npm run symbols:illustrations:sync          # write the manifest
 *   npm run symbols:illustrations:sync -- --check  # fail if it is stale
 */

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const STATIC_DIR = path.join(ROOT, 'docs-src', 'static');
const MANIFEST = path.join(ROOT, 'constants', 'symbolIllustrations.ts');
const WIDTHS = [240, 480, 1200];

const readJson = (file) => JSON.parse(fs.readFileSync(path.join(ROOT, file), 'utf8'));

function explicitIllustrations() {
  const byId = new Map();
  for (const file of ['data/dream-symbols-extended.json', 'data/dream-symbols-extended-tier3.json']) {
    const data = readJson(file);
    // `symbols` is keyed by id; the illustration lives on each localized entry.
    for (const [id, locales] of Object.entries(data.symbols || {})) {
      const src = Object.values(locales || {}).find((entry) => entry?.illustration?.src)?.illustration.src;
      if (src && !byId.has(id)) byId.set(id, src);
    }
  }
  return byId;
}

const exists = (sitePath) => fs.existsSync(path.join(STATIC_DIR, sitePath.replace(/^\/+/, '')));

// Responsive artwork resolves to its `<base>` (served as `<base>-<width>w.webp`);
// a single-size poster resolves to its full path.
function resolveSource(id, explicit, registry) {
  const responsiveBase = registry.responsiveBase || '/img/seo/symbols-v2';
  const bases = [explicit.get(id), registry.assets?.[id]?.src]
    .filter(Boolean)
    .map((src) => `${responsiveBase}/${path.basename(src, path.extname(src))}`);
  for (const base of bases) {
    if (WIDTHS.every((width) => exists(`${base}-${width}w.webp`))) return base;
  }
  const poster = `/img/symbols/posters-v1/${id}.webp`;
  return exists(poster) ? poster : null;
}

function main() {
  const check = process.argv.includes('--check');
  const symbolsData = readJson('data/dream-symbols.json');
  const ids = (symbolsData.symbols || symbolsData).map((symbol) => symbol.id).sort();
  const registry = readJson('docs-src/config/symbol-image-assets.json');
  const explicit = explicitIllustrations();

  const resolved = ids
    .map((id) => ({ id, source: resolveSource(id, explicit, registry) }))
    .filter((entry) => entry.source);
  const missing = ids.filter((id) => !resolved.some((entry) => entry.id === id));

  const manifest = [
    '// Generated by scripts/sync-symbol-illustrations.js. Do not edit by hand.',
    '// The artwork is served by the marketing site (docs-src/static on noctalia.app).',
    '',
    "import type { ImageSource } from 'expo-image';",
    '',
    "const SITE_ORIGIN = 'https://noctalia.app';",
    '',
    '// Responsive artwork is published as `<path>-<width>w.webp`; a path ending in',
    '// `.webp` is a single-size poster.',
    'const SYMBOL_ILLUSTRATION_PATHS: Readonly<Record<string, string>> = {',
    ...resolved.map(({ id, source }) => `  ${JSON.stringify(id)}: ${JSON.stringify(source)},`),
    '};',
    '',
    '// thumb: list rows (56 pt), poster: rails (140 pt), hero: the full-bleed sheet.',
    'export type SymbolIllustrationSize = keyof typeof WIDTHS;',
    `const WIDTHS = { thumb: ${WIDTHS[0]}, poster: ${WIDTHS[1]}, hero: ${WIDTHS[2]} } as const;`,
    '',
    'export function getSymbolIllustration(',
    '  id: string,',
    '  size: SymbolIllustrationSize,',
    '): ImageSource | undefined {',
    '  const sitePath = SYMBOL_ILLUSTRATION_PATHS[id];',
    '  if (!sitePath) return undefined;',
    "  if (sitePath.endsWith('.webp')) return { uri: `${SITE_ORIGIN}${sitePath}` };",
    '  return { uri: `${SITE_ORIGIN}${sitePath}-${WIDTHS[size]}w.webp` };',
    '}',
    '',
  ].join('\n');

  const stale = !fs.existsSync(MANIFEST) || fs.readFileSync(MANIFEST, 'utf8') !== manifest;
  if (check) {
    if (stale) {
      console.error('The symbol illustration manifest is stale. Run npm run symbols:illustrations:sync.');
      process.exit(1);
    }
    console.log(`Symbol illustrations up to date: ${resolved.length}/${ids.length}.`);
    return;
  }

  fs.writeFileSync(MANIFEST, manifest);
  console.log(`Synced ${resolved.length}/${ids.length} symbol illustrations.`);
  if (missing.length) console.log(`Without artwork (sky fallback): ${missing.join(', ')}`);
}

main();
