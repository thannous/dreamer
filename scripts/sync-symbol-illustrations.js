#!/usr/bin/env node
'use strict';

/**
 * Copies the site's symbol illustrations into the app bundle.
 *
 * The marketing site already owns one illustration per symbol (docs-src). The app
 * shows the same artwork on its symbol sheets, bundled so the sheet stays instant
 * and offline-capable. Re-run after the site adds or replaces an illustration:
 *
 *   npm run symbols:illustrations:sync          # write assets + manifest
 *   npm run symbols:illustrations:sync -- --check  # fail if they are stale
 */

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const STATIC_DIR = path.join(ROOT, 'docs-src', 'static');
const OUT_DIR = path.join(ROOT, 'assets', 'images', 'symbols');
const MANIFEST = path.join(ROOT, 'constants', 'symbolIllustrations.ts');
const WIDTH = 800;

const readJson = (file) => JSON.parse(fs.readFileSync(path.join(ROOT, file), 'utf8'));

function explicitIllustrations() {
  const byId = new Map();
  for (const file of ['data/dream-symbols-extended.json', 'data/dream-symbols-extended-tier3.json']) {
    const data = readJson(file);
    // `symbols` is keyed by id; the illustration lives on each localized entry.
    for (const [id, locales] of Object.entries(data.symbols || {})) {
      const src = Object.values(locales || {}).find((entry) => entry?.illustration?.src)?.illustration.src;
      if (src && !byId.has(id)) byId.set(id, src);
    }
  }
  return byId;
}

function resolveSource(id, explicit, registry) {
  const responsiveBase = registry.responsiveBase || '/img/seo/symbols-v2';
  const candidates = [explicit.get(id), registry.assets?.[id]?.src]
    .filter(Boolean)
    .map((src) => `${responsiveBase}/${path.basename(src, path.extname(src))}-${WIDTH}w.webp`);
  candidates.push(`/img/symbols/posters-v1/${id}.webp`);
  for (const candidate of candidates) {
    const file = path.join(STATIC_DIR, candidate.replace(/^\/+/, ''));
    if (fs.existsSync(file)) return file;
  }
  return null;
}

function main() {
  const check = process.argv.includes('--check');
  const symbolsData = readJson('data/dream-symbols.json');
  const ids = (symbolsData.symbols || symbolsData).map((symbol) => symbol.id).sort();
  const registry = readJson('docs-src/config/symbol-image-assets.json');
  const explicit = explicitIllustrations();

  const resolved = ids
    .map((id) => ({ id, source: resolveSource(id, explicit, registry) }))
    .filter((entry) => entry.source);
  const missing = ids.filter((id) => !resolved.some((entry) => entry.id === id));

  const manifest = [
    '// Generated by scripts/sync-symbol-illustrations.js. Do not edit by hand.',
    '// The artwork comes from the marketing site (docs-src/static).',
    '',
    'export const SYMBOL_ILLUSTRATIONS: Readonly<Record<string, number>> = {',
    ...resolved.map(({ id }) => `  ${JSON.stringify(id)}: require('@/assets/images/symbols/${id}.webp'),`),
    '};',
    '',
    'export function getSymbolIllustration(id: string): number | undefined {',
    '  return SYMBOL_ILLUSTRATIONS[id];',
    '}',
    '',
  ].join('\n');

  const stale = [];
  for (const { id, source } of resolved) {
    const target = path.join(OUT_DIR, `${id}.webp`);
    const same = fs.existsSync(target) && fs.readFileSync(target).equals(fs.readFileSync(source));
    if (same) continue;
    if (check) stale.push(id);
    else {
      fs.mkdirSync(OUT_DIR, { recursive: true });
      fs.copyFileSync(source, target);
    }
  }
  const manifestStale = !fs.existsSync(MANIFEST) || fs.readFileSync(MANIFEST, 'utf8') !== manifest;

  if (check) {
    if (stale.length || manifestStale) {
      console.error(`Symbol illustrations are stale (${stale.length} files${manifestStale ? ', manifest' : ''}). Run npm run symbols:illustrations:sync.`);
      process.exit(1);
    }
    console.log(`Symbol illustrations up to date: ${resolved.length}/${ids.length}.`);
    return;
  }

  fs.writeFileSync(MANIFEST, manifest);
  console.log(`Synced ${resolved.length}/${ids.length} symbol illustrations.`);
  if (missing.length) console.log(`Without artwork (sky fallback): ${missing.join(', ')}`);
}

main();
