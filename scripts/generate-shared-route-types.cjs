#!/usr/bin/env node
'use strict';

const fs = require('node:fs');
const path = require('node:path');
const ts = require('typescript');
const { requireContext } = require('expo-router/internal/testing');
const { getRoutes } = require('expo-router/internal/routing');
const { EXPO_ROUTER_CTX_IGNORE } = require('expo-router/_ctx-shared');
const { getTypedRoutesDeclarationFile } = require('@expo/router-server/build/typed-routes/generate');

const projectRoot = path.resolve(__dirname, '..');
const properties = ['hrefInputParams', 'hrefOutputParams', 'href'];

function routeTypes(relativeRoot) {
  const context = requireContext(path.join(projectRoot, relativeRoot), true, EXPO_ROUTER_CTX_IGNORE);
  // Expo's generator catches discovery errors. Fail this check instead of silently
  // accepting an empty route schema when a product contains invalid/duplicate routes.
  if (!getRoutes(context, {
    ignore: [/_layout\.[tj]sx?$/],
    platformRoutes: false,
    notFound: false,
    ignoreEntryPoints: true,
    ignoreRequireErrors: true,
    importMode: 'async',
  })) {
    throw new Error(`No routes found in ${relativeRoot}`);
  }
  const declaration = getTypedRoutesDeclarationFile(context);
  const source = ts.createSourceFile('router.d.ts', declaration, ts.ScriptTarget.Latest, true);
  const types = new Map();
  function visit(node) {
    if (ts.isInterfaceDeclaration(node) && node.name.text === '__routes') {
      for (const member of node.members) {
        if (ts.isPropertySignature(member) && member.type) {
          types.set(member.name.getText(source), member.type.getText(source));
        }
      }
    }
    ts.forEachChild(node, visit);
  }
  visit(source);
  if (types.size !== properties.length || properties.some((name) => !types.has(name))) {
    throw new Error(`Unsupported Expo Router declaration format for ${relativeRoot}`);
  }
  return types;
}

// Dreamer and Lucid have separate runtime roots but share one TypeScript project.
// Union the official declarations, not their route contexts: both own a '/' route.
const products = ['app', 'routes/lucid'].map(routeTypes);
const members = properties.map((name) => {
  const union = products.map((types) => `(${types.get(name)})`).join(' | ');
  return `      ${name}: ${union};`;
});
const output = [
  '/* Generated by scripts/generate-shared-route-types.cjs. Do not edit. */',
  "import * as Router from 'expo-router';",
  "export * from 'expo-router';",
  "declare module 'expo-router' {",
  '  export namespace ExpoRouter {',
  '    export interface __routes<T extends string | object = string> {',
  ...members,
  '    }',
  '  }',
  '}',
  '',
].join('\n');
const destination = path.join(projectRoot, '.expo/types/noctalia-router.d.ts');
fs.mkdirSync(path.dirname(destination), { recursive: true });
if (!fs.existsSync(destination) || fs.readFileSync(destination, 'utf8') !== output) {
  fs.writeFileSync(destination, output);
}
console.log('Generated shared Dreamer and Lucid route types.');
