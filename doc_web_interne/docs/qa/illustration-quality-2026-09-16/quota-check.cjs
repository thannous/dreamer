const { PGlite } = require('@electric-sql/pglite');
const fs = require('node:fs');
const assert = require('node:assert/strict');
const { randomUUID } = require('node:crypto');
async function main() {
 const db = new PGlite();
 await db.exec(`create role anon; create role authenticated; create role service_role bypassrls;
 create schema auth; create table auth.users(id uuid primary key, tier text default 'plus');
 create function auth.uid() returns uuid language sql as $$ select nullif(current_setting('request.jwt.claim.sub', true), '')::uuid $$;
 create table public.ai_jobs(id uuid primary key, user_id uuid, job_type text, status text, request_payload jsonb);
 create function public.get_effective_subscription_tier(p_user_id uuid) returns text language sql as $$ select tier from auth.users where id=p_user_id $$;`);
 await db.exec(fs.readFileSync(require('node:path').join(process.cwd(), 'supabase/migrations/20260916185856_hd_illustration_monthly_quota.sql'),'utf8'));
 const owner=randomUUID(), other=randomUUID(), free=randomUUID();
 for(const id of [owner,other,free]) await db.query('insert into auth.users(id) values ($1)',[id]);
 await db.query("update auth.users set tier='free' where id=$1",[free]);
 const job=async (user=owner) => {const id=randomUUID(); await db.query("insert into ai_jobs values ($1,$2,'generate_image','running','{\"imageSize\":\"4K\"}')",[id,user]); return id;};
 const reserve=async (id,user=owner)=>(await db.query('select reserve_hd_image_credit($1,$2) as result',[user,id])).rows[0].result;
 const jobs=await Promise.all(Array.from({length:20},()=>job()));
 const results=await Promise.all(jobs.map(id=>reserve(id)));
 assert.equal(results.filter(r=>r.allowed).length,15);
 assert.equal(results.filter(r=>r.code==='HD_IMAGE_QUOTA_EXCEEDED').length,5);
 assert.equal((await reserve(jobs[0])).duplicate,true);
 assert.equal((await reserve(await job(free),free)).code,'HD_IMAGE_PLUS_REQUIRED');
 assert.equal((await reserve(jobs[0],other)).code,'HD_IMAGE_INVALID_JOB');
 assert.equal((await reserve(await job(other),other)).allowed,true);
 await db.query("update ai_jobs set status='failed' where id=$1",[jobs[0]]);
 await db.query('select finish_hd_image_credit($1,false)',[jobs[0]]);
 assert.equal((await reserve(jobs[15])).allowed,true);
 await db.query("update ai_jobs set status='succeeded' where id=$1",[jobs[1]]);
 await db.query('select finish_hd_image_credit($1,true)',[jobs[1]]);
 await db.query('select finish_hd_image_credit($1,false)',[jobs[1]]);
 assert.equal((await db.query('select state from hd_image_credits where job_id=$1',[jobs[1]])).rows[0].state,'completed');
 await db.query("select set_config('request.jwt.claim.sub',$1,false)",[owner]);
 await db.exec('set role authenticated');
 const quota=(await db.query('select get_hd_image_quota() as result')).rows[0].result;
 assert.equal(quota.limit,15);assert.equal(quota.remaining,0);
 await assert.rejects(()=>db.query('select reserve_hd_image_credit($1,$2)',[owner,jobs[16]]),/permission denied/);
 await assert.rejects(()=>db.query('select * from hd_image_credits'),/permission denied/);
 await db.exec('reset role');
 await db.exec("update hd_image_credits set period_start=(date_trunc('month',now() at time zone 'UTC')-interval '1 month')::date");
 assert.equal((await reserve(jobs[16])).allowed,true);
 await db.query("select set_config('request.jwt.claim.sub','',false)");
 await assert.rejects(()=>db.query('select get_hd_image_quota()'),/Authentication required/);
 console.log('PASS: actual PostgreSQL migration; 20 queued requests capped at 15, idempotency, account isolation, Plus gate, terminal refund, completed-credit protection, monthly rollover, authenticated status and role permissions. PGlite serializes queries; true multi-process contention is not measured.');
 await db.close();
}
main().catch(e=>{console.error(e.message);process.exitCode=1;});
